// Checks touch and mouse control as it really runs: real clicks, real animation loop.
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1180, height: 820 }, hasTouch: true });
page.on('pageerror', (e) => console.log('PAGE ERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('console error:', m.text()); });
await page.goto('http://localhost:5173/');
await page.waitForFunction(() => window.game);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.game);
await page.waitForTimeout(800);
const at = (x, y, z) => page.evaluate(([x, y, z]) => game.pixel.toScreen(game.V(x, y, z)), [x, y, z]);
const state = () => page.evaluate(() => ({ players: game.players.map((p) => p.dev.id), mama: game.mama.state + ' ' + game.mama.pos.toArray().map((v) => v.toFixed(1)), region: game.world.region, hud: document.getElementById('hud').className, title: document.getElementById('title').className, goal: game.goal && game.goal.pick.kind }));
await page.touchscreen.tap(590, 410);
await page.waitForTimeout(600);
console.log('after first tap', JSON.stringify(await state()));
let s = await at(3.5, 0, -2.5);
await page.touchscreen.tap(s.x, s.y);
await page.waitForTimeout(2600);
console.log('after tapping the lawn', JSON.stringify(await state()));
await page.screenshot({ path: 'tools/out/touch-1.png' });
const flap = await page.evaluate(() => { const p = game.world.portals.find((q) => q.to === 'home'); return game.pixel.toScreen(game.V(p.x, p.y + 0.35, p.z)); });
await page.mouse.click(flap.x, flap.y);
await page.waitForTimeout(4500);
console.log('after clicking the cat flap', JSON.stringify(await state()));
await page.click('#hud [data-act=nap]');
await page.waitForTimeout(700);
console.log('after the moon icon', JSON.stringify(await state()));
await page.click('#hud [data-act=paw]');
await page.waitForTimeout(400);
await page.screenshot({ path: 'tools/out/touch-2.png' });
console.log('menu open', await page.evaluate(() => game.menu.open));
await browser.close();
